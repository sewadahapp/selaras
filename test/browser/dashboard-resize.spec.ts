test('controls desktop collapse, restores width, and keeps mobile drawer state separate', async ({ page, goto }) => {
  await page.setViewportSize({ width: 1200, height: 800 })
  await goto('/?controlled=true', { waitUntil: 'hydration' })
  const sidebar = page.locator('#sidebar')
  await expect(sidebar).toHaveAttribute('data-state', 'collapsed')
  await expect.poll(async () => (await sidebar.boundingBox())!.width).toBeCloseTo(64, 0)
  await page.locator('#set-expand').click()
  await expect(sidebar).toHaveAttribute('data-state', 'expanded')
  await expect.poll(async () => (await sidebar.boundingBox())!.width).toBeCloseTo(260, 0)
  await page.locator('#sidebar-toggle').click()
  await expect(page.locator('#collapse-model')).toHaveText('true')
  await page.locator('#method-expand').click()
  await expect(page.locator('#collapse-model')).toHaveText('false')
  await page.locator('#method-collapse').click()
  await expect(sidebar).toHaveAttribute('data-state', 'collapsed')
  await page.setViewportSize({ width: 600, height: 800 })
  await expect(sidebar).toHaveCount(0)
  await page.locator('#method-expand').click()
  await expect(page.locator('#collapse-model')).toHaveText('true')
  await page.locator('#set-expand').click()
  await page.setViewportSize({ width: 1200, height: 800 })
  await expect(sidebar).toHaveAttribute('data-state', 'expanded')
})

