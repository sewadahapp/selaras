test('collapsed labels open on hover and focus without breaking links or child flyouts', async ({ page, goto }) => {
  await goto('/', { waitUntil: 'hydration' })
  const account = page.getByRole('link', { name: 'Account', exact: true })
  await account.hover()
  await expect(page.getByRole('tooltip', { includeHidden: true })).toHaveText('Account')
  await expect(page.locator('[data-side="right"]:has([role="tooltip"])')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.mouse.move(1100, 700)
  await page.keyboard.press('Tab')
  await account.focus()
  await expect(page.getByRole('tooltip', { includeHidden: true })).toHaveText('Account')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Team', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Members' })).toBeVisible()
  await expect(page.locator('[role="dialog"][data-side="left"]')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Team', exact: true })).toBeFocused()
})

test('keeps uncontrolled collapse persisted and lets an explicit value override it', async ({ page, goto, context }) => {
  await page.setViewportSize({ width: 1200, height: 800 })
  await goto('/', { waitUntil: 'hydration' })
  const sidebar = page.locator('#sidebar')
  await expect.poll(async () => (await sidebar.boundingBox())!.width).toBeCloseTo(260, 0)
  await page.locator('#sidebar-toggle').click()
  await expect(sidebar).toHaveAttribute('data-state', 'collapsed')
  await expect.poll(async () => {
    const cookie = (await context.cookies()).find(cookie => cookie.name === 'resize-regression')
    if (!cookie)
      return undefined
    const saved = JSON.parse(decodeURIComponent(cookie.value)) as Record<string, { layout: number[] }>
    return Object.values(saved)[0]?.layout[0]
  }).toBeCloseTo(6.4, 1)
  await page.reload()
  await expect(sidebar).toHaveAttribute('data-state', 'collapsed')
  await goto('/?controlled=false', { waitUntil: 'hydration' })
  await expect(sidebar).toHaveAttribute('data-state', 'expanded')
  await expect(page.locator('#collapse-model')).toHaveText('false')
})

