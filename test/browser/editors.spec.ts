import { fileURLToPath } from 'node:url'
import { expect, test } from '@nuxt/test-utils/playwright'
import { toolbarContract } from './helpers/toolbar-contract'

test.use({ nuxt: { rootDir: fileURLToPath(new URL('../fixtures/editors', import.meta.url)) } })
toolbarContract()

for (const engine of ['tiptap', 'lexical', 'quill']) {
  test(`${engine} preserves selection through formatting and link dialogs, syncs content and supports read-only mode`, async ({ page, goto }) => {
    const issues: string[] = []
    page.on('pageerror', error => issues.push(error.message))
    page.on('console', (message) => {
      if (/hydration|mismatch|Failed to resolve component/i.test(message.text()))
        issues.push(message.text())
    })
    await goto(`/?engine=${engine}`, { waitUntil: 'hydration' })
    const block = page.locator(`[data-editor-engine=${engine}]`)
    const editor = block.getByRole('textbox', { name: 'Project note', exact: true })
    const toolbar = block.getByRole('toolbar')
    await expect(editor).toBeVisible()
    await expect(toolbar.getByRole('button', { name: 'Bold', exact: true })).toBeEnabled()
    await expect(editor).not.toBeFocused()
    await editor.click()
    await page.keyboard.press('ControlOrMeta+A')
    await page.keyboard.type('Hello team')
    await page.keyboard.press('ControlOrMeta+A')
    await toolbar.getByRole('button', { name: 'Bold', exact: true }).click()
    await expect(editor.locator('strong,b')).toHaveText('Hello team')
    await expect(toolbar.getByRole('button', { name: 'Bold', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await toolbar.getByRole('button', { name: 'Undo', exact: true }).click()
    await expect(editor.locator('strong,b')).toHaveCount(0)
    await toolbar.getByRole('button', { name: 'Redo', exact: true }).click()
    await expect(editor.locator('strong,b')).toHaveText('Hello team')
    await editor.focus()
    await page.keyboard.press('ControlOrMeta+A')
    await page.keyboard.press('ControlOrMeta+I')
    await expect(toolbar.getByRole('button', { name: 'Italic', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await toolbar.getByRole('button', { name: 'Edit link', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByRole('textbox', { name: 'Link address', exact: true }).fill('https://example.com/notes')
    await dialog.getByRole('button', { name: 'Apply link', exact: true }).click()
    await expect(dialog).toBeHidden()
    await expect(editor).toBeFocused()
    await expect(editor.locator('a')).toHaveAttribute('href', 'https://example.com/notes')
    await expect(page.locator('#model')).toContainText('https://example.com/notes')
    await toolbar.getByRole('button', { name: 'Heading', exact: true }).click()
    await expect(editor.locator('h2')).toContainText('Hello team')
    await toolbar.getByRole('button', { name: 'Bullet list', exact: true }).click()
    await expect(editor.locator('li').first()).toContainText('Hello team')
    await block.getByText('Read only', { exact: true }).click()
    await expect(editor).toHaveAttribute('contenteditable', 'false')
    for (const button of await toolbar.getByRole('button').all()) await expect(button).toBeDisabled()
    await page.locator('#external').click()
    await expect(editor).toHaveText('External replacement')
    await block.getByText('Read only', { exact: true }).click()
    await page.locator('#empty').click()
    await expect(editor).toHaveText('')
    await expect(page.locator('#model')).toBeEmpty()
    await page.locator('#mount-tiptap').click()
    await page.locator('#mount-lexical').click()
    await page.locator('#mount-quill').click()
    await expect(page.locator('[data-editor-engine=quill] [role=textbox]')).toBeVisible()
    expect(issues).toEqual([])
  })
}
